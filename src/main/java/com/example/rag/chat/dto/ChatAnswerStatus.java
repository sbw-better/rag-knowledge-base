package com.example.rag.chat.dto;

/**
 * 问答结果状态。
 *
 * <p>RAG 问答不应在没有知识库证据时让模型自由发挥。该状态用于告诉前端：
 * 本次回答是基于检索上下文生成，还是因为空知识库/无命中而返回了固定提示。</p>
 */
public enum ChatAnswerStatus {
    /**
     * 已命中知识库上下文，并完成模型回答。
     */
    ANSWERED,

    /**
     * 当前知识库还没有任何可用于问答的文档切片。
     */
    EMPTY_KB,

    /**
     * 知识库有资料，但本次问题没有检索到可用上下文。
     */
    NO_CONTEXT,

    /**
     * 用户输入是问候、感谢或轻量闲聊，不需要检索知识库。
     */
    CASUAL
}
